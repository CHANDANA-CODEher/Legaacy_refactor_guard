"""End-to-End Refactoring Demonstration Script for Legacy Refactor Guard.

Executes RefactorAgent on demo_repo/shop.py using MockLLMProvider.
Records baseline metrics, validates syntax, applies the refactoring safely,
verifies all tests pass, and writes the standardized run_log.json.
"""

from __future__ import annotations

import json
from pathlib import Path

from agent.agent import RefactorAgent
from agent.llm import MockLLMProvider

REFACTORED_SHOP_CODE = """\"\"\"E-commerce shopping cart calculation module.

[MOCK REFACTOR - LOCAL SIMULATION ONLY]
Notice: Generated by MockLLMProvider for offline testing.
This was NOT generated by a real Nebius AI model.
Goal: Simplify calculate_order_total, add type annotations and constants.
\"\"\"

from __future__ import annotations

TAX_RATE: float = 0.08
STANDARD_SHIPPING: float = 5.00
FREE_SHIPPING_THRESHOLD: float = 50.00

CUSTOMER_DISCOUNTS: dict[str, float] = {
    "vip": 0.20,
    "premium": 0.10,
    "standard": 0.0,
}


def calculate_order_total(
    items: list[dict[str, float | int]] | None,
    customer_type: str = "standard",
    coupon_code: str | None = None,
) -> float:
    \"\"\"Calculate the final order total including membership discounts, coupons, shipping, and tax.

    Args:
        items: List of dictionary items with 'price' and 'quantity'.
        customer_type: Customer membership tier ('standard', 'premium', 'vip').
        coupon_code: Optional coupon code ('SAVE10', 'FREESHIP').

    Returns:
        Final rounded order total as a float.
    \"\"\"
    if not items:
        return 0.0

    # 1. Calculate raw items subtotal
    subtotal = sum(
        float(item["price"]) * int(item["quantity"])
        for item in items
        if "price" in item and "quantity" in item
    )

    # 2. Apply customer membership tier discount
    normalized_tier = customer_type.strip().lower() if customer_type else "standard"
    discount_rate = CUSTOMER_DISCOUNTS.get(normalized_tier, 0.0)
    subtotal_after_membership = subtotal * (1.0 - discount_rate)

    # 3. Apply coupon code
    discounted_subtotal = subtotal_after_membership
    free_shipping_coupon = False

    if coupon_code:
        normalized_coupon = coupon_code.strip().upper()
        if normalized_coupon == "SAVE10":
            discounted_subtotal = max(0.0, discounted_subtotal - 10.0)
        elif normalized_coupon == "FREESHIP":
            free_shipping_coupon = True

    # 4. Shipping fee calculation
    if discounted_subtotal >= FREE_SHIPPING_THRESHOLD or free_shipping_coupon:
        shipping_fee = 0.0
    else:
        shipping_fee = STANDARD_SHIPPING

    # 5. Tax calculation (8% on final discounted subtotal)
    tax = round(discounted_subtotal * TAX_RATE, 2)

    # 6. Final total
    return round(discounted_subtotal + tax + shipping_fee, 2)
"""


def main() -> None:
    repo_path = Path("demo_repo")
    target_file = "shop.py"
    goal = "Refactor calculate_order_total with type hints, constants, and clean discount mapping"

    # Configure deterministic mock provider with the clean refactored version
    mock_provider = MockLLMProvider(responses=[REFACTORED_SHOP_CODE])

    print("=" * 70)
    print("LEGACY REFACTOR GUARD - END-TO-END DEMO RUN")
    print(f"Target Repository: {repo_path}")
    print(f"Target File:       {target_file}")
    print(f"Provider:          {mock_provider.name} (Deterministic Mock)")
    print(f"Goal:              {goal}")
    print("=" * 70)

    agent = RefactorAgent(
        repo_path=repo_path,
        provider=mock_provider,
        log_path="run_log.json",
        archive_existing_logs=True,
    )

    result = agent.run(target_file=target_file, goal=goal)

    print("\n--- RUN OUTCOME ---")
    print(f"Success:       {result.success}")
    print(f"Status:        {result.status}")
    print(f"Message:       {result.message}")
    print(f"Baseline:      Passed: {result.baseline['passed']}, Failed: {result.baseline['failed']}")
    print(f"Final:         Passed: {result.final['passed']}, Failed: {result.final['failed']}")
    print(f"Files Changed: {result.files_changed}")

    # Inspect run_log.json
    log_path = Path("run_log.json")
    if log_path.exists():
        print(f"\n--- run_log.json contents ({log_path.resolve()}) ---")
        log_data = json.loads(log_path.read_text(encoding="utf-8"))
        print(json.dumps(log_data, indent=2))


if __name__ == "__main__":
    main()
