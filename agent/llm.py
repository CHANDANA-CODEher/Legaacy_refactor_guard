"""LLM provider interface and implementations for Legacy Refactor Guard.

Provides:
- LLMProvider: Abstract base interface for refactoring providers.
- MockLLMProvider: Deterministic local mock provider for offline development.
- NebiusLLMProvider: Configurable provider for Nebius Token Factory API.
- get_llm_provider: Factory function driven by configuration/environment.
"""

from __future__ import annotations

import os
import re
from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Any

import requests


class LLMError(Exception):
    """Base exception for all LLM provider errors."""


class MissingCredentialsError(LLMError):
    """Raised when required API credentials are missing."""


class LLMAPIError(LLMError):
    """Raised when an external LLM API request fails (network error, timeout, HTTP error)."""


class MalformedResponseError(LLMError):
    """Raised when an API response cannot be parsed into valid code."""


@dataclass(frozen=True)
class RefactorResponse:
    """Standardized response from an LLM refactoring request."""

    code: str
    provider: str
    model: str
    explanation: str = ""
    is_mock: bool = False


def extract_code_from_llm_response(raw_text: str) -> str:
    """Extract Python source code from LLM response text.

    Strips markdown code fences (```python ... ``` or ``` ... ```) if present.
    Does NOT execute or import any code.

    Args:
        raw_text: Text returned by LLM.

    Returns:
        Cleaned Python code string.
    """
    text = raw_text.strip()
    if not text:
        return ""

    # Check for ```python ... ``` or ``` ... ``` block
    pattern = r"```(?:python)?\s*\n(.*?)\n```"
    match = re.search(pattern, text, re.DOTALL | re.IGNORECASE)
    if match:
        return match.group(1).strip()

    # Fallback: check if text is enclosed by triple backticks without newline
    if text.startswith("```") and text.endswith("```"):
        lines = text.splitlines()
        if len(lines) >= 2:
            return "\n".join(lines[1:-1]).strip()

    return text


class LLMProvider(ABC):
    """Abstract interface for LLM refactoring providers."""

    @property
    @abstractmethod
    def name(self) -> str:
        """Provider identifier ('mock' or 'nebius')."""
        ...

    @abstractmethod
    def refactor(
        self,
        source_code: str,
        goal: str,
        test_feedback: str | None = None,
    ) -> RefactorResponse:
        """Generate refactored Python source code.

        Args:
            source_code: Original Python code to refactor.
            goal: Description of the refactoring goal.
            test_feedback: Optional output from previous failed test runs.

        Returns:
            RefactorResponse containing refactored code and metadata.
        """
        ...


class MockLLMProvider(LLMProvider):
    """Deterministic local mock provider for development and offline testing.

    Explicitly labeled as mock mode. Never claims to be a real AI model.
    """

    def __init__(
        self,
        responses: list[str] | None = None,
        default_code: str | None = None,
        model_name: str = "mock-deterministic-v1",
    ) -> None:
        """Initialize mock provider.

        Args:
            responses: Optional queue of scripted code strings to return sequentially.
            default_code: Optional fallback code when responses queue is empty.
            model_name: Descriptive name for the mock model.
        """
        self._responses = list(responses) if responses else []
        self._default_code = default_code
        self._model_name = model_name
        self.call_count = 0

    @property
    def name(self) -> str:
        return "mock"

    def refactor(
        self,
        source_code: str,
        goal: str,
        test_feedback: str | None = None,
    ) -> RefactorResponse:
        """Return deterministic mock refactored code.

        Does not call external APIs. Clearly marked as mock simulation.
        """
        self.call_count += 1

        if self._responses:
            code = self._responses.pop(0)
        elif self._default_code is not None:
            code = self._default_code
        else:
            # Generate deterministic code with explicit mock banner
            banner = (
                f"# [MOCK REFACTOR - LOCAL SIMULATION ONLY]\n"
                f"# Notice: Generated by MockLLMProvider for offline testing.\n"
                f"# This was NOT generated by a real Nebius AI model.\n"
                f"# Goal: {goal}\n"
            )
            # Remove any existing mock banner to avoid stacking
            clean_source = re.sub(
                r"^# \[MOCK REFACTOR - LOCAL SIMULATION ONLY\].*?# Goal: .*?\n",
                "",
                source_code,
                flags=re.DOTALL,
            ).lstrip()
            code = banner + clean_source

        return RefactorResponse(
            code=code,
            provider=self.name,
            model=self._model_name,
            explanation=(
                f"[MOCK MODE] Deterministic mock refactor attempt #{self.call_count} "
                f"for goal: {goal}"
            ),
            is_mock=True,
        )


class NebiusLLMProvider(LLMProvider):
    """Real LLM provider using the Nebius Token Factory API (OpenAI-compatible).

    Reads API key and endpoint configuration from environment variables.
    Fails safely if credentials are not configured.
    """

    DEFAULT_BASE_URL = "https://api.studio.nebius.ai/v1"
    DEFAULT_MODEL = "meta-llama/Meta-Llama-3.1-70B-Instruct"

    def __init__(
        self,
        api_key: str | None = None,
        base_url: str | None = None,
        model: str | None = None,
        timeout: float = 30.0,
    ) -> None:
        """Initialize Nebius provider.

        Args:
            api_key: Nebius API key (reads NEBIUS_API_KEY env var if None).
            base_url: API base URL (reads NEBIUS_BASE_URL env var if None).
            model: Model identifier (reads NEBIUS_MODEL env var if None).
            timeout: Network request timeout in seconds.

        Raises:
            MissingCredentialsError: If API key is empty or not provided.
        """
        resolved_key = (api_key or os.getenv("NEBIUS_API_KEY", "")).strip()
        if not resolved_key:
            raise MissingCredentialsError(
                "Nebius API key is missing. Set the NEBIUS_API_KEY environment variable "
                "or pass api_key to NebiusLLMProvider. For offline local development, "
                "use MockLLMProvider or set LLM_PROVIDER=mock."
            )

        self.api_key = resolved_key
        self.base_url = (base_url or os.getenv("NEBIUS_BASE_URL", self.DEFAULT_BASE_URL)).rstrip("/")
        self.model = model or os.getenv("NEBIUS_MODEL", self.DEFAULT_MODEL)
        self.timeout = float(timeout)

    @property
    def name(self) -> str:
        return "nebius"

    def __repr__(self) -> str:
        # Never expose full API key in representations or logs
        masked = f"{self.api_key[:4]}...{self.api_key[-4:]}" if len(self.api_key) > 8 else "***"
        return (
            f"NebiusLLMProvider(base_url={self.base_url!r}, model={self.model!r}, "
            f"api_key={masked!r}, timeout={self.timeout})"
        )

    def _build_prompt(
        self,
        source_code: str,
        goal: str,
        test_feedback: str | None = None,
    ) -> list[dict[str, str]]:
        """Construct system and user messages for refactoring."""
        system_content = (
            "You are a senior Python refactoring engineer. Your job is to safely refactor "
            "Python code according to the stated goal while keeping all existing functionality "
            "and tests intact.\n"
            "CRITICAL INSTRUCTIONS:\n"
            "1. Output ONLY the complete refactored Python source code inside a ```python ... ``` block.\n"
            "2. Do not omit code or use placeholders like '# ... rest of code'.\n"
            "3. Do not include introductory text or commentary outside the code block."
        )

        user_content = f"Refactoring Goal: {goal}\n\nOriginal Code:\n```python\n{source_code}\n```"
        if test_feedback:
            user_content += (
                f"\n\nPrevious Test Failures / Feedback:\n{test_feedback}\n"
                "Please fix these failures while fulfilling the goal."
            )

        return [
            {"role": "system", "content": system_content},
            {"role": "user", "content": user_content},
        ]

    def refactor(
        self,
        source_code: str,
        goal: str,
        test_feedback: str | None = None,
    ) -> RefactorResponse:
        """Send refactoring request to Nebius Token Factory API.

        Args:
            source_code: Original code to refactor.
            goal: Refactoring goal.
            test_feedback: Optional feedback from previous failed tests.

        Returns:
            RefactorResponse with the extracted refactored code.

        Raises:
            LLMAPIError: On network errors, timeouts, or non-200 HTTP responses.
            MalformedResponseError: When API returns invalid JSON or unexpected schema.
        """
        endpoint = f"{self.base_url}/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model,
            "messages": self._build_prompt(source_code, goal, test_feedback),
            "temperature": 0.2,
        }

        try:
            response = requests.post(
                endpoint,
                json=payload,
                headers=headers,
                timeout=self.timeout,
            )
            response.raise_for_status()
        except requests.exceptions.Timeout as exc:
            raise LLMAPIError(
                f"Nebius API request timed out after {self.timeout}s."
            ) from exc
        except requests.exceptions.HTTPError as exc:
            status = exc.response.status_code if exc.response is not None else "unknown"
            raise LLMAPIError(f"Nebius API returned HTTP error {status}: {exc}") from exc
        except requests.exceptions.RequestException as exc:
            raise LLMAPIError(
                f"Nebius API network request failed: {type(exc).__name__}"
            ) from exc

        # Parse JSON response safely
        try:
            data = response.json()
        except Exception as exc:
            raise MalformedResponseError(
                f"Nebius API returned invalid JSON: {exc}"
            ) from exc

        if not isinstance(data, dict):
            raise MalformedResponseError(
                f"Nebius API response is not a JSON object: {type(data).__name__}"
            )

        choices = data.get("choices")
        if not choices or not isinstance(choices, list):
            raise MalformedResponseError(
                "Nebius API response is missing a valid 'choices' list."
            )

        first_choice = choices[0]
        if not isinstance(first_choice, dict):
            raise MalformedResponseError(
                "Nebius API response choice is not a valid object."
            )

        message = first_choice.get("message")
        if not message or not isinstance(message, dict) or "content" not in message:
            raise MalformedResponseError(
                "Nebius API response is missing 'message.content'."
            )

        raw_content = message["content"]
        if not isinstance(raw_content, str):
            raise MalformedResponseError(
                "Nebius API 'message.content' is not a string."
            )

        extracted_code = extract_code_from_llm_response(raw_content)
        if not extracted_code:
            raise MalformedResponseError(
                "Nebius API response did not contain any usable Python code."
            )

        return RefactorResponse(
            code=extracted_code,
            provider=self.name,
            model=self.model,
            explanation=f"Refactored by Nebius model {self.model}",
            is_mock=False,
        )


def get_llm_provider(
    provider_type: str | None = None,
    **kwargs: Any,
) -> LLMProvider:
    """Factory to instantiate the configured LLM provider.

    Args:
        provider_type: Optional explicit provider name ('mock' or 'nebius').
                       If None, reads the LLM_PROVIDER environment variable (defaults to 'mock').
        **kwargs: Additional arguments passed to provider constructor.

    Returns:
        Configured LLMProvider instance.

    Raises:
        ValueError: If provider_type is unsupported.
        MissingCredentialsError: If 'nebius' is chosen but credentials are missing.
    """
    chosen = (provider_type or os.getenv("LLM_PROVIDER", "mock")).strip().lower()

    if chosen == "mock":
        return MockLLMProvider(**kwargs)
    elif chosen == "nebius":
        return NebiusLLMProvider(**kwargs)
    else:
        raise ValueError(
            f"Unsupported LLM provider '{chosen}'. Supported options are 'mock' and 'nebius'."
        )
